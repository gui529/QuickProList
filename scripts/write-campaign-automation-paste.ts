/**
 * Write secrets/campaign-automation-paste.env for Cursor Automation .env paste.
 *
 * Run ONLY via Vercel (decrypted production env):
 *   npx vercel env run -e production -- npx tsx scripts/write-campaign-automation-paste.ts
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const outPath = resolve(import.meta.dirname, '..', 'secrets', 'campaign-automation-paste.env')

const unsub = process.env.UNSUBSCRIBE_SECRET?.trim() ?? ''
const cron = process.env.CRON_SECRET?.trim() ?? ''
const secret = unsub.length >= 16 ? unsub : cron.length >= 16 ? cron : unsub || cron

if (!secret || secret.length < 8) {
  console.error(
    'Could not read a usable UNSUBSCRIBE_SECRET or CRON_SECRET from Vercel production.\n' +
      'Set CRON_SECRET (or UNSUBSCRIBE_SECRET) on Vercel → home-help → Production, then re-run:\n' +
      '  npx vercel env run -e production -- npx tsx scripts/write-campaign-automation-paste.ts'
  )
  process.exit(1)
}

const body = `# Generated by scripts/write-campaign-automation-paste.ts — gitignored. Paste into Cursor Automation → Environment.
# Source: Vercel production ${unsub.length >= 16 ? 'UNSUBSCRIBE_SECRET' : 'CRON_SECRET'}

UNSUBSCRIBE_SECRET=${secret}
`

writeFileSync(outPath, body, 'utf8')
console.log(`Wrote ${outPath} (UNSUBSCRIBE_SECRET, ${secret.length} chars). Paste file contents into Campaign Loop env — do not commit.`)
